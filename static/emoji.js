    var currentInput = null;

    // Создаём панель
    function createPanel() {
        var panel = document.createElement('div');
        panel.className = 'emoji-panel';
        panel.id = 'emoji-panel';
        
        var html = '';
        for (var category in EMOJI_CATEGORIES) {
            html += '<div class="emoji-category-title">' + category + '</div>';
            html += '<div class="emoji-grid">';
            EMOJI_CATEGORIES[category].forEach(function(emoji) {
                html += '<button type="button" class="emoji-item" data-emoji="' + emoji + '">' + emoji + '</button>';
            });
            html += '</div>';
        }
        
        panel.innerHTML = html;
        document.body.appendChild(panel);
        
        // Клик на эмодзи — вставляем
        panel.addEventListener('click', function(e) {
            var btn = e.target.closest('.emoji-item');
            if (!btn || !currentInput) return;
            
            var emoji = btn.getAttribute('data-emoji');
            var start = currentInput.selectionStart;
            var end = currentInput.selectionEnd;
            var text = currentInput.value;
            
            currentInput.value = text.substring(0, start) + emoji + text.substring(end);
            currentInput.selectionStart = currentInput.selectionEnd = start + emoji.length;
            currentInput.focus();
        });
        
        return panel;
    }

    var panel = null;

    window.openEmojiPicker = function(button, input) {
        currentInput = input;
        
        if (!panel) {
            panel = createPanel();
        }
        
        var rect = button.getBoundingClientRect();
        panel.style.top = (rect.bottom + window.scrollY + 4) + 'px';
        panel.style.left = Math.max(10, rect.left + window.scrollX - 150) + 'px';
        panel.style.display = 'block';
    };

    window.closeEmojiPicker = function() {
        if (panel) {
            panel.style.display = 'none';
        }
    };

    // Закрываем при клике вне панели
    document.addEventListener('click', function(e) {
        if (!panel) return;
        if (!panel.contains(e.target) && !e.target.closest('.emoji-trigger')) {
            panel.style.display = 'none';
        }
    });

    // Инициализация всех кнопок-триггеров
    document.addEventListener('DOMContentLoaded', function() {
        document.querySelectorAll('.emoji-trigger').forEach(function(btn) {
            btn.addEventListener('click', function(e) {
                e.preventDefault();
                var targetId = btn.getAttribute('data-target');
                var input = document.getElementById(targetId);
                if (input) {
                    window.openEmojiPicker(btn, input);
                }
            });
        });
    });
